def _slug(text):
    out = "".join(_MAP.get(c, c) for c in text.lower())
    return re.sub(r"[^a-z0-9]+", "-", out).strip("-")


def article(label, slug=None):
    return {"label": label, "kind": "article", "target": slug or _slug(label)}


def tool(label, slug):
    return {"label": label, "kind": "tool", "target": slug}


def catalog(label, target):
    return {"label": label, "kind": "catalog", "target": target}


